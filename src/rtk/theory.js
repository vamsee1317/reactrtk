// Redux Toolkit Theory :

// RTK is built on top of Redux.
// RTK is nothing mini database for your state management in Frontend Applications.
// RTK is used to write Redux Logic with less code and more efficiency.
// RTK provides good developer experience with useful tools and abstractions.


// Core Principles of RTK :

// 1. Slice  : A mini module containing state + reducers + actions for a specific feature.
// 2. Store : The centralized place to hold the entire application state. (Global State Container).
// 3. Dispatch : A method to send actions to the store to update the state. (Used to trigger state changes).
// 4. Selector : A function to extract specific pieces of state from the store. (Used to read state).
// 5. Thunk : A middleware to handle asynchronous logic in Redux. (Used for async actions like API calls).